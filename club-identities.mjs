const identities = new Map();
const searchNames = new Map(clubGroups.map(names=>[names[0],names.join(' ')]));
for (const names of clubGroups) for (const name of names) {
 const key=clubKey(name);
 if(identities.has(key)&&identities.get(key)!==names[0]) throw new Error('Conflicting club alias: '+name);
 identities.set(key,names[0]);
}
export const canonicalClub = name => identities.get(clubKey(name)) || String(name ?? '').trim();
export const clubSearchNames = name => searchNames.get(canonicalClub(name)) || String(name ?? '');
const nonClubs = new Set(['?','unknown','null','Free Agent','Retired','NBA','NBA (Draft)','NBA (OKC)','College (USA)','Italian Serie A2','Spanish league'].map(clubKey));
export const isClub = name => !!clubKey(name) && !nonClubs.has(clubKey(name));
